let ident = Walk.ident

(* How a field is stored is a [Layout.store], the codec's layout. *)

(* A field of the record, read from the codec's plan: its name, the Rust name
   its functions and record field derive from, the variable that holds its
   value as an [i64] in the checks, where it sits in the record, how it is
   stored, the plan's checks on it and the cases of its closed enum. *)
type field = {
  name : string;
  lit : string;
  doc : string;
  label : string;
  var : string;
  off : int;
  store : store;
  checks : P.check list;
  enum : int list option;
}

(* {1 Layout}

   The flat module covers a record of leaves: integers up to 32 bits,
   bitfields and byte arrays, each under refinements and closed or open enums,
   every field named. Its layout, its checks and their order are the plan's. *)

let rec leaf_field : type a. a T.typ -> unit = function
  | T.Where { inner; _ } -> leaf_field inner
  | T.Enum { base; _ } -> leaf_field base
  | T.Map _ -> fail_unsupported "a map, which Rust code cannot call"
  | T.Bits _ -> ()
  | typ ->
      if Option.is_none (leaf typ) then
        fail_unsupported "its type, %a" T.pp_typ typ

let check_leaves (s : T.struct_) =
  List.iter
    (fun (T.Field f) ->
      match f.field_name with
      | None -> fail_unsupported "an anonymous field"
      | Some name -> (
          try leaf_field f.field_typ
          with Unsupported why -> fail_unsupported "field %s: %s" name why))
    s.fields

let field_of ~base (f : P.field) =
  List.iter
    (fun (c : P.check) ->
      match c.kind with
      | Tag -> fail_unsupported "field %s: a lookup" f.name
      | Constraint | Enum _ -> ())
    f.checks;
  {
    name = f.name;
    lit = rust_string f.name;
    doc = doc_string f.name;
    label = ident f.name;
    var = f.id;
    off = base + f.offset;
    store = f.store;
    checks = f.checks;
    enum = Option.map snd f.enum;
  }

(* The fields of a fixed record in order, at their offsets in it, its size and
   its [where] clauses, from the plan [p]. *)
let layout p =
  let rec go base fields tests = function
    | [] -> (List.rev fields, base, List.rev tests)
    | P.Prefix (fs, size) :: rest ->
        let fields = List.rev_append (List.map (field_of ~base) fs) fields in
        go (base + size) fields tests rest
    | P.Test cond :: rest -> go base fields (cond :: tests) rest
    | (P.Span _ | P.Gate _ | P.Region _) :: _ ->
        fail_unsupported "its size is not fixed"
  in
  go 0 [] [] (P.nodes p)

(* {1 Rust} *)

let rust_type f =
  match f.store with
  | Int { width = 8; signed; _ } -> if signed then "i8" else "u8"
  | Int { width = 16; signed; _ } -> if signed then "i16" else "u16"
  | Int { signed; _ } -> if signed then "i32" else "u32"
  | Bits { width; _ } -> bits_type width
  | Bytes n -> Fmt.str "[u8; %d]" n

(* The parameter of [write] that takes a field's value: prefixed, so no field
   name shadows the buffer, the offset or a function the body calls. *)
let arg f = "v_" ^ f.label

(* The value a write or a setter takes. *)
let arg_type f =
  match f.store with Bytes n -> Fmt.str "&[u8; %d]" n | _ -> rust_type f

(* A field's value, read from the array [b] holding the record (at [base]
   0) or the field alone (at the field's offset). *)
let read ?(rel = 0) b f =
  let k = f.off - rel in
  match f.store with
  | Int { width = 8; signed; _ } ->
      if signed then Fmt.str "(%s[%d] as i8)" b k else Fmt.str "%s[%d]" b k
  | Int { width; endian; _ } -> load b k (width / 8) endian (rust_type f)
  | Bits { base; shift; width } ->
      of_word ~base ~shift ~width
        (load b k (Bitfield.byte_size base) (base_endian base) (base_type base))
  | Bytes n ->
      Fmt.str "{ let mut a = [0u8; %d]; a.copy_from_slice(&%s[%d..%d]); a }" n b
        k (k + n)

let header ~codec ~digest ~size =
  [
    Fmt.str
      "//! Generated by Wire_rust from %s. Do not edit: generate it again when"
      (doc_string codec);
    "//! the codec changes.";
    "//!";
    "//! Every function takes the buffer as a slice and the record's offset in";
    "//! it, and reads or writes no byte outside the record. The code needs";
    "//! nothing but `core`, and no unsafe code.";
    "";
    "#![forbid(unsafe_code)]";
    "#![allow(dead_code, non_snake_case, unused_parens, unused_variables, \
     clippy::all)]";
    "";
    Fmt.str "/// The codec this module was generated from.";
    Fmt.str "pub const CODEC: &str = %s;" (rust_string codec);
    "";
    "/// The digest of the codec's description, which changes whenever the";
    "/// bytes it accepts or the values it reads do.";
    Fmt.str "pub const DIGEST: &str = %s;" (rust_string digest);
    "";
    "/// The size of the record in bytes.";
    Fmt.str "pub const SIZE: usize = %d;" size;
    "";
  ]

let error_prelude =
  {|/// Why a read or a write was refused.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Error {
    /// The buffer holds fewer than `expected` bytes, the end of the record
    /// or of the field, but `got`.
    TooShort { expected: usize, got: usize },
    /// The constraint of `field` fails, or the record's `where` clause when
    /// `field` is empty. `at` is the offset of the field in the buffer, or
    /// of the record.
    Constraint { field: &'static str, at: usize },
    /// `field`, a closed enum at offset `at`, holds `value`, which is none of
    /// its cases.
    InvalidEnum { field: &'static str, at: usize, value: i64 },
    /// A value handed to a write does not fit its bitfield, or is not a case
    /// of its closed enum.
    OutOfRange { field: &'static str, value: i64 },
}

|}

let frame_prelude =
  {|#[inline(always)]
fn frame(buf: &[u8], off: usize) -> Result<&[u8; SIZE], Error> {
    match buf.get(off..).and_then(|b| b.first_chunk::<SIZE>()) {
        Some(b) => Ok(b),
        None => Err(Error::TooShort { expected: off.saturating_add(SIZE), got: buf.len() }),
    }
}

#[inline(always)]
fn frame_mut(buf: &mut [u8], off: usize) -> Result<&mut [u8; SIZE], Error> {
    let got = buf.len();
    match buf.get_mut(off..).and_then(|b| b.first_chunk_mut::<SIZE>()) {
        Some(b) => Ok(b),
        None => Err(Error::TooShort { expected: off.saturating_add(SIZE), got }),
    }
}

#[inline(always)]
fn field<const N: usize>(buf: &[u8], off: usize, at: usize) -> Result<&[u8; N], Error> {
    match buf.get(off..).and_then(|b| b.get(at..)).and_then(|b| b.first_chunk::<N>()) {
        Some(b) => Ok(b),
        None => Err(Error::TooShort { expected: off.saturating_add(at + N), got: buf.len() }),
    }
}

#[inline(always)]
fn field_mut<const N: usize>(buf: &mut [u8], off: usize, at: usize) -> Result<&mut [u8; N], Error> {
    let got = buf.len();
    match buf.get_mut(off..).and_then(|b| b.get_mut(at..)).and_then(|b| b.first_chunk_mut::<N>()) {
        Some(b) => Ok(b),
        None => Err(Error::TooShort { expected: off.saturating_add(at + N), got }),
    }
}
|}

let prelude = error_prelude ^ shift_prelude ^ "\n" ^ frame_prelude

let member v cases =
  Fmt.str "(%a)"
    Fmt.(list ~sep:(any " || ") (fun ppf c -> pf ppf "%s == %s" v (int_lit c)))
    cases

let pp_record ppf fields =
  Fmt.pf ppf
    "/// The record's field values.@\n\
     #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]@\n\
     pub struct Record {@\n";
  List.iter
    (fun f -> Fmt.pf ppf "    pub %s: %s,@\n" f.label (rust_type f))
    fields;
  Fmt.pf ppf "}@\n@\n"

(* A check of the record: one of a field's, or a [where] clause. *)
type step = On of field * P.check | Where of bool T.expr

(* Where [f] ends in the record. *)
let field_end f = f.off + width_bytes f.store

(* The checks of a record that fits, in the codec's order: each field's in
   field order, then the [where] clauses. *)
let fit_steps ~fields ~where =
  List.concat_map (fun f -> List.map (fun c -> On (f, c)) f.checks) fields
  @ List.map (fun w -> Where w) where

(* The checks of a record that does not fit, in the order 3D makes them: a
   [where] clause comes after the last field it reads, as the refinement of
   that field the projection makes it, or before every field when it reads
   none. *)
let short_steps ~fields ~where =
  let reads w f = List.mem f.var (T.collect_refs w) in
  let after f w =
    match List.rev (List.filter (reads w) fields) with
    | last :: _ -> last.var = f.var
    | [] -> false
  in
  let first = List.filter (fun w -> not (List.exists (reads w) fields)) where in
  List.map (fun w -> Where w) first
  @ List.concat_map
      (fun f ->
        List.map (fun c -> On (f, c)) f.checks
        @ List.map (fun w -> Where w) (List.filter (after f) where))
      fields

(* Where the bytes a step reads end: those of its field, or of the last field
   a [where] clause reads. *)
let step_end ~fields = function
  | On (f, _) -> field_end f
  | Where w ->
      List.fold_left
        (fun acc f ->
          if List.mem f.var (T.collect_refs w) then max acc (field_end f)
          else acc)
        0 fields

(* The reads of the fields' values, then [steps], each written under what the
   checks before it established, returning [fail ~at e] when it fails with
   the error [e], its bytes ending at [at]. *)
let pp_steps ppf ~plan ~fields ~fail steps =
  List.iter
    (fun f ->
      match f.store with
      | Bytes _ -> ()
      | _ -> Fmt.pf ppf "    let %s = %s as i64;@\n" f.var (read "b" f))
    fields;
  ignore
    (List.fold_left
       (fun scope step ->
         let at = step_end ~fields step in
         let cond, err =
           match step with
           | On (f, c) ->
               let err =
                 match c.kind with
                 | Enum _ ->
                     Fmt.str
                       "Error::InvalidEnum { field: %s, at: off + %d, value: \
                        %s }"
                       f.lit f.off f.var
                 | Constraint | Tag ->
                     Fmt.str "Error::Constraint { field: %s, at: off + %d }"
                       f.lit f.off
               in
               (c.cond, err)
           | Where w -> (w, "Error::Constraint { field: \"\", at: off }")
         in
         Fmt.pf ppf "    if !(%s) { return %s; }@\n" (expr scope cond)
           (fail ~at err);
         P.Scope.refine scope [ cond ])
       (P.Scope.v plan) steps)

(* [check] makes the codec's checks on a record in an array, in its order. *)
let pp_check ppf ~plan ~fields ~where =
  Fmt.pf ppf
    "#[inline(always)]@\n\
     fn check(b: &[u8; SIZE], off: usize) -> Result<(), Error> {@\n";
  pp_steps ppf ~plan ~fields
    ~fail:(fun ~at:_ e -> Fmt.str "Err(%s)" e)
    (fit_steps ~fields ~where);
  Fmt.pf ppf "    Ok(())@\n}@\n@\n"

(* [short] is the error of a record that does not fit at [off]: its checks run
   on the bytes there are, padded with zeros, and the first that fails is the
   error when its bytes are there, else the end of input. *)
let pp_short ppf ~plan ~fields ~where =
  Fmt.pf ppf
    "#[cold]@\n\
     #[inline(never)]@\n\
     fn short(buf: &[u8], off: usize) -> Error {@\n\
    \    let too_short = Error::TooShort { expected: off.saturating_add(SIZE), \
     got: buf.len() };@\n";
  let steps = short_steps ~fields ~where in
  if steps <> [] then begin
    Fmt.pf ppf
      "    let rest = match buf.get(off..) { Some(r) => r, None => return \
       too_short };@\n\
      \    let avail = rest.len().min(SIZE);@\n\
      \    let mut padded = [0u8; SIZE];@\n\
      \    padded[..avail].copy_from_slice(&rest[..avail]);@\n\
      \    let b = &padded;@\n";
    pp_steps ppf ~plan ~fields
      ~fail:(fun ~at e ->
        Fmt.str "if %d > avail { too_short } else { %s }" at e)
      steps
  end;
  Fmt.pf ppf "    too_short@\n}@\n@\n"

let pp_record_of ppf ~b fields =
  Fmt.pf ppf "Record {@\n";
  List.iter (fun f -> Fmt.pf ppf "        %s: %s,@\n" f.label (read b f)) fields;
  Fmt.pf ppf "    }"

let pp_entry ppf ~fields =
  Fmt.pf ppf
    "/// Checks the record at `off` as the codec's `validate` does.@\n\
     #[inline]@\n\
     pub fn validate(buf: &[u8], off: usize) -> Result<(), Error> {@\n\
    \    check(frame(buf, off).map_err(|_| short(buf, off))?, off)@\n\
     }@\n\
     @\n\
     /// Checks and reads the record at `off`, as the codec's `decode` does.@\n\
     #[inline]@\n\
     pub fn decode(buf: &[u8], off: usize) -> Result<Record, Error> {@\n\
    \    let b = frame(buf, off).map_err(|_| short(buf, off))?;@\n\
    \    check(b, off)?;@\n\
    \    Ok(%a)@\n\
     }@\n\
     @\n"
    (pp_record_of ~b:"b") fields

(* A write stores each value of a bitfield word once, or-ed into place. *)
let bit_words fields =
  List.filter_map
    (fun f ->
      match f.store with Bits { base; _ } -> Some (f.off, base) | _ -> None)
    fields
  |> List.sort_uniq compare

let store_word ppf ~b (o, base) fields =
  let ty = base_type base in
  let parts =
    List.filter_map
      (fun f ->
        match f.store with
        | Bits { shift; _ } when f.off = o ->
            Fmt.kstr Option.some "((%s as %s) << %d)" (arg f) ty shift
        | _ -> None)
      fields
  in
  let value = String.concat " | " parts in
  match base with
  | T.U8 -> Fmt.pf ppf "    %s[%d] = %s;@\n" b o value
  | T.U16 e | T.U32 e ->
      let n = Bitfield.byte_size base in
      Fmt.pf ppf "    %s[%d..%d].copy_from_slice(&(%s).to_%s_bytes());@\n" b o
        (o + n) value (endian_suffix e)

let store ppf ~b ~v ~rel f =
  let k = f.off - rel in
  match f.store with
  | Int { width = 8; signed; _ } ->
      Fmt.pf ppf "    %s[%d] = %s%s;@\n" b k v (if signed then " as u8" else "")
  | Int { width; endian; _ } ->
      Fmt.pf ppf "    %s[%d..%d].copy_from_slice(&%s.to_%s_bytes());@\n" b k
        (k + (width / 8))
        v (endian_suffix endian)
  | Bytes n -> Fmt.pf ppf "    %s[%d..%d].copy_from_slice(%s);@\n" b k (k + n) v
  | Bits _ -> ()

(* The refusals a write makes before it stores anything: a bitfield's value
   wider than the field, and a value outside a closed enum, in field order. *)
let pp_range ppf ~v f =
  (match f.store with
  | Bits { width; _ } when width < type_bits width ->
      Fmt.pf ppf
        "    if %s >> %d != 0 { return Err(Error::OutOfRange { field: %s, \
         value: %s as i64 }); }@\n"
        v width f.lit v
  | _ -> ());
  match f.enum with
  | Some cases ->
      Fmt.pf ppf
        "    if !%s { return Err(Error::OutOfRange { field: %s, value: %s as \
         i64 }); }@\n"
        (member (Fmt.str "(%s as i64)" v) cases)
        f.lit v
  | None -> ()

let pp_write ppf ~fields =
  Fmt.pf ppf
    "/// Writes a record of these values at `off`, as the codec's `encode`@\n\
     /// does: a value that does not fit its field is refused before any byte@\n\
     /// is written, and a record that fails its constraints after.@\n\
     #[inline]@\n\
     pub fn write(buf: &mut [u8], off: usize%a) -> Result<(), Error> {@\n\
    \    let b = frame_mut(buf, off)?;@\n"
    Fmt.(list ~sep:nop (fun ppf f -> pf ppf ", %s: %s" (arg f) (arg_type f)))
    fields;
  List.iter (fun f -> pp_range ppf ~v:(arg f) f) fields;
  List.iter (fun w -> store_word ppf ~b:"b" w fields) (bit_words fields);
  List.iter (fun f -> store ppf ~b:"b" ~v:(arg f) ~rel:0 f) fields;
  Fmt.pf ppf "    check(b, off)@\n}@\n@\n";
  Fmt.pf ppf
    "/// Writes `r` at `off`, as [`write`] does.@\n\
     #[inline]@\n\
     pub fn encode(r: &Record, buf: &mut [u8], off: usize) -> Result<(), \
     Error> {@\n\
    \    write(buf, off%a)@\n\
     }@\n\
     @\n"
    Fmt.(
      list ~sep:nop (fun ppf f ->
          match f.store with
          | Bytes _ -> pf ppf ", &r.%s" f.label
          | _ -> pf ppf ", r.%s" f.label))
    fields

(* [get_<field>] reads one field as the codec's getter does: from the bytes of
   the field alone, with no check of the other fields or of constraints; a
   closed enum's value is checked to be a case. *)
let pp_getter ppf f =
  let n = width_bytes f.store in
  match f.store with
  | Bytes _ ->
      Fmt.pf ppf
        "/// Reads the field `%s`.@\n\
         #[inline]@\n\
         pub fn get_%s(buf: &[u8], off: usize) -> Result<&[u8; %d], Error> {@\n\
        \    field::<%d>(buf, off, %d)@\n\
         }@\n\
         @\n"
        f.doc f.label n n f.off
  | _ ->
      let enum_check =
        match f.enum with
        | Some cases ->
            Fmt.str
              "    if !%s { return Err(Error::InvalidEnum { field: %s, at: \
               off.saturating_add(%d), value: v as i64 }); }@\n"
              (member "(v as i64)" cases)
              f.lit f.off
        | None -> ""
      in
      Fmt.pf ppf
        "/// Reads the field `%s`.@\n\
         #[inline]@\n\
         pub fn get_%s(buf: &[u8], off: usize) -> Result<%s, Error> {@\n\
        \    let s = field::<%d>(buf, off, %d)?;@\n\
        \    let v = %s;@\n\
         %s    Ok(v)@\n\
         }@\n\
         @\n"
        f.doc f.label (rust_type f) n f.off (read ~rel:f.off "s" f) enum_check

(* A bitfield's word, read once for all the fields packed in it:
   [get_<field>_word] loads the word that holds the field, and
   [<field>_of_word] takes the field out of it. *)
let pp_word_getters ppf f =
  match f.store with
  | Bits { base; shift; width } ->
      let n = width_bytes f.store and wt = base_type base in
      Fmt.pf ppf
        "/// Reads the word that holds the bitfield `%s`, for [`%s_of_word`].@\n\
         #[inline]@\n\
         pub fn get_%s_word(buf: &[u8], off: usize) -> Result<%s, Error> {@\n\
        \    let s = field::<%d>(buf, off, %d)?;@\n\
        \    Ok(%s)@\n\
         }@\n\
         @\n\
         /// Takes the bitfield `%s` out of its word.@\n\
         #[inline]@\n\
         pub fn %s_of_word(w: %s) -> %s {@\n\
        \    %s@\n\
         }@\n\
         @\n"
        f.doc f.label f.label wt n f.off
        (load "s" 0 n (base_endian base) wt)
        f.doc f.label wt (bits_type width)
        (of_word ~base ~shift ~width "w")
  | _ -> ()

(* [set_<field>] writes one field from its bytes alone, a bitfield's
   neighbours kept, with no check of constraints. *)
let pp_setter ppf f =
  let n = width_bytes f.store in
  Fmt.pf ppf
    "/// Writes the field `%s`, with no check of the record's constraints.@\n\
     #[inline]@\n\
     pub fn set_%s(buf: &mut [u8], off: usize, v: %s) -> Result<(), Error> {@\n\
    \    let s = field_mut::<%d>(buf, off, %d)?;@\n"
    f.doc f.label (arg_type f) n f.off;
  pp_range ppf ~v:"v" f;
  (match f.store with
  | Bits { base; shift; width } ->
      let wt = base_type base in
      let cur = load "s" 0 n (base_endian base) wt in
      let next =
        Fmt.str "(%s & !(%s%s << %d)) | ((v as %s) << %d)" cur (mask width) wt
          shift wt shift
      in
      if n = 1 then Fmt.pf ppf "    s[0] = %s;@\n" next
      else
        Fmt.pf ppf "    *s = (%s).to_%s_bytes();@\n" next
          (endian_suffix (base_endian base))
  | _ -> store ppf ~b:"s" ~v:"v" ~rel:f.off f);
  Fmt.pf ppf "    Ok(())@\n}@\n@\n"

let pp_accessors ppf f =
  pp_getter ppf f;
  pp_word_getters ppf f;
  pp_setter ppf f

(* A read of [Valid]: a load at a constant offset of its array. *)
let pp_valid_read ppf f =
  match f.store with
  | Bytes n ->
      Fmt.pf ppf
        "@\n\
        \    /// The field `%s`.@\n\
        \    #[inline]@\n\
        \    pub fn %s(&self) -> &'a [u8; %d] {@\n\
        \        let b: &'a [u8; SIZE] = self.0;@\n\
        \        b[%d..%d].try_into().unwrap()@\n\
        \    }@\n"
        f.doc f.label n f.off (f.off + n)
  | _ ->
      Fmt.pf ppf
        "@\n\
        \    /// The field `%s`.@\n\
        \    #[inline]@\n\
        \    pub fn %s(&self) -> %s {@\n\
        \        let b = self.0;@\n\
        \        %s@\n\
        \    }@\n"
        f.doc f.label (rust_type f) (read "b" f)

(* [Valid] holds a record that passed every check. Its reads index an array of
   [SIZE] bytes at constant offsets, which the compiler proves in bounds, and
   the shared borrow keeps the bytes from changing while it lives. *)
let pp_valid ppf ~fields =
  Fmt.pf ppf
    "/// A record that passed every check, as the codec's `valid` returns: its@\n\
     /// reads are loads at constant offsets with no check of their own, and@\n\
     /// the borrow keeps its bytes from changing, so they keep holding.@\n\
     #[derive(Clone, Copy, Debug)]@\n\
     pub struct Valid<'a>(&'a [u8; SIZE]);@\n\
     @\n\
     impl<'a> Valid<'a> {@\n\
    \    /// Checks the record at offset 0 of `buf`.@\n\
    \    #[inline]@\n\
    \    pub fn new(buf: &'a [u8]) -> Result<Self, Error> {@\n\
    \        Self::at(buf, 0)@\n\
    \    }@\n\
     @\n\
    \    /// Checks the record at `off` in `buf`.@\n\
    \    #[inline]@\n\
    \    pub fn at(buf: &'a [u8], off: usize) -> Result<Self, Error> {@\n\
    \        let b = frame(buf, off).map_err(|_| short(buf, off))?;@\n\
    \        check(b, off)?;@\n\
    \        Ok(Valid(b))@\n\
    \    }@\n\
     @\n\
    \    /// The record's bytes.@\n\
    \    #[inline]@\n\
    \    pub fn as_bytes(&self) -> &'a [u8; SIZE] {@\n\
    \        self.0@\n\
    \    }@\n\
     @\n\
    \    /// The record's field values.@\n\
    \    #[inline]@\n\
    \    pub fn to_record(&self) -> Record {@\n\
    \        let b = self.0;@\n\
    \    %a@\n\
    \    }@\n\
     %a}@\n"
    (pp_record_of ~b:"b") fields
    Fmt.(list ~sep:nop pp_valid_read)
    fields

(* {1 Names} *)

let refuse ~codec reason =
  Fmt.invalid_arg "Wire_rust: cannot specialise %s: %s" codec reason

(* The functions the module defines for itself. *)
let own_values =
  [
    "validate";
    "decode";
    "encode";
    "write";
    "check";
    "frame";
    "frame_mut";
    "field";
    "field_mut";
    "int";
    "add";
    "sub";
    "mul";
    "lsl";
    "lsr";
  ]

(* The methods [Valid] defines for itself. *)
let own_methods = [ "new"; "at"; "as_bytes"; "to_record" ]

let values_of f =
  let l = f.label in
  let derived =
    match f.store with
    | Bits _ -> [ "get_" ^ l ^ "_word"; l ^ "_of_word" ]
    | Int _ | Bytes _ -> []
  in
  ("get_" ^ l) :: ("set_" ^ l) :: derived

type source = Own | Field of string

let check_clash ~codec idents =
  match Wire.Private.Names.clash idents with
  | Some (Own, Field f, n) | Some (Field f, Own, n) ->
      Fmt.kstr (refuse ~codec)
        "field %S defines %s, which the generated module defines for itself" f n
  | Some (Field g, Field f, n) ->
      Fmt.kstr (refuse ~codec) "fields %S and %S both define %s" g f n
  | Some (Own, Own, _) | None -> ()

let check_names ~codec fields =
  let own l = List.map (fun n -> (Own, n)) l in
  check_clash ~codec
    (own own_values
    @ List.concat_map
        (fun f -> List.map (fun n -> (Field f.name, n)) (values_of f))
        fields);
  check_clash ~codec
    (own own_methods @ List.map (fun f -> (Field f.name, f.label)) fields)

let digest c = Wire.Private.Gen.digest c

(* {1 Structured scanners} *)

let scan_header ~codec ~digest ~slots =
  [
    Fmt.str
      "//! Generated by Wire_rust from %s. Do not edit: generate it again when"
      (doc_string codec);
    "//! the codec changes.";
    "//!";
    "//! [`scan`] checks one frame, a slice, as the codec's `decode` does and";
    "//! returns its scalar fields; [`decode`] first cuts the frame out of a";
    "//! larger buffer. Each region is a sub-slice that holds exactly its \
     bytes,";
    "//! so no read leaves the region it belongs to. The code needs nothing but";
    "//! `core`, and no unsafe code.";
    "";
    "#![forbid(unsafe_code)]";
    "#![allow(dead_code, non_snake_case, unused_parens, unused_variables, \
     clippy::all)]";
  ]
  @ (if slots then
       [
         "// An optional field that is always present overwrites its outputs' \
          absent";
         "// values, and one that never is leaves them.";
         "#![allow(unused_assignments, unused_mut)]";
       ]
     else [])
  @ [
      "";
      "/// The codec this module was generated from.";
      Fmt.str "pub const CODEC: &str = %s;" (rust_string codec);
      "";
      "/// The digest of the codec's description, which changes whenever the";
      "/// bytes it accepts or the values it reads do.";
      Fmt.str "pub const DIGEST: &str = %s;" (rust_string digest);
      "";
    ]

let scan_prelude = shift_prelude

let pp_scan_fields ppf outputs =
  Fmt.pf ppf
    "/// The scalar fields of an accepted frame, named by their path in the@\n\
     /// codec; an absent optional's are zero, its [`_present`] flag false.@\n\
     #[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]@\n\
     pub struct Fields {@\n";
  List.iter
    (fun (o : P.output) ->
      Fmt.pf ppf "    pub %s: %s,@\n" (ident o.name) (output_type o))
    outputs;
  Fmt.pf ppf "}@\n@\n"

let scan_result outputs =
  Fmt.str "Some(Fields {%a })"
    Fmt.(
      list ~sep:(any ",") (fun ppf (o : P.output) ->
          if o.is_bool then pf ppf " %s: %s" (ident o.name) o.id
          else pf ppf " %s: %s as %s" (ident o.name) o.id (output_type o)))
    outputs

let scan_check_names ~codec outputs =
  match
    Wire.Private.Names.clash
      (List.map (fun (o : P.output) -> ((o.id, o.name), ident o.name)) outputs)
  with
  | Some ((_, a), (_, b), n) when a = b ->
      Fmt.kstr (refuse ~codec) "two outputs are named %S, the Rust field %s" a n
  | Some ((_, a), (_, b), n) ->
      Fmt.kstr (refuse ~codec) "outputs %S and %S both define the Rust field %s"
        a b n
  | None -> ()

let pp_scanner ?fields ~codec ppf c =
  let plan, outputs =
    match P.v c with
    | plan -> (
        match P.select plan fields with
        | outputs -> (plan, outputs)
        | exception Invalid_argument reason -> refuse ~codec reason)
    | exception Invalid_argument reason -> refuse ~codec reason
  in
  scan_check_names ~codec (P.outputs plan);
  let code, slots =
    try
      body ~depth:1 plan outputs ~frame:"frame" ~finish:[ scan_result outputs ]
    with Unsupported reason -> refuse ~codec reason
  in
  let header = scan_header ~codec ~digest:(digest c) ~slots in
  pp_lines ppf header;
  Fmt.pf ppf "%s@\n" scan_prelude;
  pp_scan_fields ppf outputs;
  Fmt.pf ppf
    "/// Checks the frame `frame`, all of it the codec may read, and returns \
     its@\n\
     /// fields, or `None` when the codec rejects it.@\n\
     #[inline(always)]@\n\
     pub fn scan(frame: &[u8]) -> Option<Fields> {@\n\
     %s}@\n\
     @\n\
     /// Checks the frame of `len` bytes at `off` in `buf`, as [`scan`] does; \
     `None`@\n\
     /// too when the frame does not lie inside `buf`.@\n\
     #[inline]@\n\
     pub fn decode(buf: &[u8], off: usize, len: usize) -> Option<Fields> {@\n\
    \    let end = off.checked_add(len)?;@\n\
    \    scan(buf.get(off..end)?)@\n\
     }@\n"
    code

let scanner ?fields ~codec c = Fmt.str "%a" (pp_scanner ?fields ~codec) c

(* The plan of a flat module: that of a record of leaves. *)
let flat_plan c =
  match check_leaves (Wire.Private.Gen.to_struct c) with
  | exception Unsupported reason -> Error reason
  | () -> (
      match P.v c with
      | plan -> Ok plan
      | exception Invalid_argument reason -> Error reason)

let pp ~codec ppf c =
  let plan =
    match flat_plan c with Ok p -> p | Error reason -> refuse ~codec reason
  in
  match layout plan with
  | exception Unsupported reason -> refuse ~codec reason
  | _, size, _ when Wire.Codec.size c <> Some size ->
      refuse ~codec "its size is not fixed"
  | fields, size, where ->
      check_names ~codec fields;
      pp_lines ppf (header ~codec ~digest:(digest c) ~size);
      Fmt.pf ppf "%s@\n" prelude;
      pp_record ppf fields;
      pp_check ppf ~plan ~fields ~where;
      pp_short ppf ~plan ~fields ~where;
      pp_entry ppf ~fields;
      pp_write ppf ~fields;
      List.iter (pp_accessors ppf) fields;
      pp_valid ppf ~fields

let rs ~codec c = Fmt.str "%a" (pp ~codec) c

(* {1 The module of a codec} *)

type fold = Rust_module.fold

let fold ?outputs name = { Rust_module.name; outputs; visitor = None }

type t =
  | T : { name : string; folds : fold list; codec : 'r Wire.Codec.t } -> t

(* What [Wire_ocaml] refuses, refused with its message. *)
let ocaml_refuses folds c =
  let folds =
    List.map (fun (f : fold) -> Wire_ocaml.fold ?outputs:f.outputs f.name) folds
  in
  match Wire_ocaml.v ~target:`OCaml ~folds c with
  | m -> Wire_ocaml.name m
  | exception Invalid_argument msg ->
      let prefix = "Wire_ocaml:" in
      if String.starts_with ~prefix msg then
        invalid_arg
          ("Wire_rust:"
          ^ String.sub msg (String.length prefix)
              (String.length msg - String.length prefix))
      else invalid_arg msg

(* The visitor a rule names: a Rust path, or a file [x_y.rs], whose type
   [XY] the crate declares as the module [x_y]. *)
let visitor_path v =
  if Filename.check_suffix v ".rs" then
    let stem = Filename.remove_extension (Filename.basename v) in
    let camel =
      String.concat ""
        (List.map String.capitalize_ascii (String.split_on_char '_' stem))
    in
    Fmt.str "crate::%s::%s" stem camel
  else v

let source ?(visitors = []) (T t) =
  let folds =
    List.map
      (fun (f : fold) ->
        match List.assoc_opt f.name visitors with
        | None -> f
        | Some v -> { f with visitor = Some (visitor_path v) })
      t.folds
  in
  List.iter
    (fun (n, _) ->
      if not (List.exists (fun (f : fold) -> f.name = n) t.folds) then
        Fmt.invalid_arg "Wire_rust: %s declares no fold %S" t.name n)
    visitors;
  Rust_module.rs ~codec:(Wire.Private.Gen.to_struct t.codec).name ~folds t.codec

let v ?name ?(folds = [ fold "fold" ]) codec =
  let default = ocaml_refuses folds codec in
  let name = Option.value ~default name in
  let t = T { name; folds; codec } in
  (* Refused when declared, not when printed. *)
  ignore (source t : string);
  t

let name (T t) = t.name
let to_rs ?visitors t = source ?visitors t

(* {2 The generator's command line} *)

let usage =
  "usage: gen.exe [--visitor FOLD=TYPE]... FILE...\n\
   Writes each FILE, <name>.rs, the module <name>; FOLD of each written module \
   is visited by TYPE, a Rust path or a file x_y.rs of the crate, whose type \
   is XY."

let fail fmt =
  Fmt.kstr
    (fun msg ->
      Fmt.epr "%s: %s@.%s@." Sys.executable_name msg usage;
      exit 2)
    fmt

let rec parse visitors files = function
  | [] -> (List.rev visitors, List.rev files)
  | "--visitor" :: v :: rest -> (
      match String.index_opt v '=' with
      | Some i ->
          let fold = String.sub v 0 i
          and typ = String.sub v (i + 1) (String.length v - i - 1) in
          parse ((fold, typ) :: visitors) files rest
      | None -> fail "--visitor %s: expected FOLD=TYPE" v)
  | "--visitor" :: [] -> fail "--visitor needs FOLD=TYPE"
  | file :: rest -> parse visitors (file :: files) rest

let write file text =
  let oc = open_out_bin file in
  output_string oc text;
  close_out oc

let main ts =
  let visitors, files = parse [] [] (List.tl (Array.to_list Sys.argv)) in
  if files = [] then fail "no file to write";
  let declares (T t) fold =
    List.exists (fun (f : fold) -> f.name = fold) t.folds
  in
  let written =
    List.map
      (fun file ->
        let stem =
          match String.split_on_char '.' (Filename.basename file) with
          | stem :: "rs" :: _ -> stem
          | _ -> fail "%s: not a .rs file" file
        in
        match List.find_opt (fun t -> name t = stem) ts with
        | None ->
            fail "%s: no module %s among %s" file stem
              (String.concat ", " (List.map name ts))
        | Some t -> (file, t))
      files
  in
  List.iter
    (fun (fold, typ) ->
      if not (List.exists (fun (_, t) -> declares t fold) written) then
        fail "--visitor %s=%s: no module written declares a fold %s" fold typ
          fold)
    visitors;
  List.iter
    (fun (file, t) ->
      let visitors = List.filter (fun (fold, _) -> declares t fold) visitors in
      write file (to_rs ~visitors t))
    written
