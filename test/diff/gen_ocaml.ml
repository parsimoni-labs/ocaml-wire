(* Writes [ocaml_index.ml]: a module generated by [Wire_ocaml] for every codec
   of [Diff_ocaml.codecs] it accepts, each wrapped in the glue that hands
   its functions to [Diff_ocaml] under one type, and the codecs it refused with
   its reason. [--oxcaml] generates for the OxCaml target. *)

open Wire.Private
module T = Types

let target =
  if Array.exists (String.equal "--oxcaml") Sys.argv then `OxCaml else `OCaml

type field = {
  name : string;
  ident : string;
  show : string;
  views : Diff_ocaml.view list;
}

let fields c =
  List.map
    (fun (T.Field f) ->
      let name = Option.get f.field_name in
      let show =
        match Diff_ocaml.show_code f.field_typ with
        | Some s -> s
        | None ->
            Fmt.failwith "gen: field %s has a type the backend cannot show" name
      in
      {
        name;
        ident = Wire_ocaml.ident name;
        show;
        views = Diff_ocaml.views f.field_typ;
      })
    (Gen.to_struct c).fields

let view = function
  | Diff_ocaml.Get -> "Diff_ocaml.Get"
  | Get_int -> "Diff_ocaml.Get_int"
  | Of_word -> "Diff_ocaml.Of_word"

(* Each getter of [f] in module [m], on the buffer [buf] makes from [b]. *)
let pp_gets ~m ~buf ppf f =
  List.iter
    (fun v ->
      let read =
        match v with
        | Diff_ocaml.Get -> Fmt.str "%s (%s.get_%s (%s) o)" f.show m f.ident buf
        | Get_int ->
            Fmt.str "string_of_int (%s.get_%s_int (%s) o)" m f.ident buf
        | Of_word ->
            Fmt.str "string_of_int (%s.%s_of_word (%s.get_%s_word (%s) o))" m
              f.ident m f.ident buf
      in
      Fmt.pf ppf "        (%S, %s, fun b o -> %s);@\n" f.name (view v) read)
    f.views

(* The reads after [Valid.v]: a [read_<f>] for every field, and a
   [read_<f>_int] for a 32-bit one. *)
let reads fields =
  List.concat_map
    (fun f ->
      List.filter_map
        (function
          | Diff_ocaml.Get -> Some (f, Diff_ocaml.Get)
          | Get_int -> Some (f, Get_int)
          | Of_word -> None)
        f.views)
    fields

let pp_read ~m ppf (f, v) =
  match v with
  | Diff_ocaml.Get -> Fmt.pf ppf "%s (%s.read_%s v)" f.show m f.ident
  | _ -> Fmt.pf ppf "string_of_int (%s.read_%s_int v)" m f.ident

(* The glue over [m] ("M" or "M.Bigstring"), whose buffer [buf] makes from
   the bytes [b]; [back] wraps a write so its bytes land in [b]. *)
let pp_ops ppf ~m ~buf ~back fields =
  let reads = reads fields in
  Fmt.pf ppf
    "{@\n\
    \      Diff_ocaml.decode =@\n\
    \        (fun b o ->@\n\
    \          let out = Bytes.create M.size in@\n\
    \          M.encode (%s.decode (%s) o) out 0;@\n\
    \          Bytes.to_string out);@\n\
    \      validate = (fun b o -> %s.validate (%s) o);@\n\
    \      encode =@\n\
    \        (fun s b o ->@\n\
    \          let r = M.decode (Bytes.of_string s) 0 in@\n\
    \          %a);@\n\
    \      gets = [@\n\
     %a      ];@\n\
    \      reads = [ %a ];@\n\
    \      valid = (fun b -> let v = %s.Valid.v (%s) in [ %a ]);@\n\
    \    }"
    m buf m buf back (Fmt.str "%s.encode r" m)
    Fmt.(list ~sep:nop (pp_gets ~m ~buf))
    fields
    Fmt.(
      list ~sep:(any "; ") (fun ppf (f, v) -> pf ppf "(%S, %s)" f.name (view v)))
    reads m buf
    Fmt.(list ~sep:(any "; ") (pp_read ~m))
    reads

let pp_case ppf (label, c, src) =
  let fields = fields c in
  Fmt.pf ppf
    "let %s : Fuzz_gen.packed -> Diff_ocaml.t = function@\n\
    \  | Fuzz_gen.Pack g ->@\n\
    \  let codec = Fuzz_gen.codec g in@\n\
    \  let module M = struct@\n\
     %s@\n\
    \  end in@\n\
    \  {@\n\
    \    Diff_ocaml.bytes =@\n\
    \      %a;@\n\
    \    bigstring =@\n\
    \      %a;@\n\
    \  }@\n\
     @\n"
    label src
    (pp_ops ~m:"M" ~buf:"b" ~back:(fun ppf w -> Fmt.pf ppf "%s b o" w))
    fields
    (pp_ops ~m:"M.Bigstring" ~buf:"Diff_ocaml.big b" ~back:(fun ppf w ->
         Fmt.pf ppf
           "let bb = Diff_ocaml.big b in %s bb o; Diff_ocaml.blit_back bb b" w))
    fields

let () =
  let ppf = Format.std_formatter in
  let accepted, refused =
    List.partition_map
      (fun (label, Fuzz_gen.Pack g) ->
        let c = Fuzz_gen.codec g in
        match Wire_ocaml.ml ~target ~codec:"codec" c with
        | src -> Left (label, Fuzz_gen.Pack g, src)
        | exception Invalid_argument msg -> Right (label, msg))
      Diff_ocaml.codecs
  in
  Fmt.pf ppf
    "(* Generated by test/diff/gen_ocaml.exe from the codecs of \
     Diff_ocaml.codecs. *)@\n\
     @\n";
  Fmt.pf ppf "let name = %S@\n@\n"
    (match target with `OCaml -> "ocaml" | `OxCaml -> "oxcaml");
  List.iteri
    (fun i (_, Fuzz_gen.Pack g, src) ->
      pp_case ppf (Fmt.str "case_%d" i, Fuzz_gen.codec g, src))
    accepted;
  Fmt.pf ppf
    "let covered : (string * (Fuzz_gen.packed -> Diff_ocaml.t)) list =@\n  [@\n";
  List.iteri
    (fun i (label, _, _) -> Fmt.pf ppf "    (%S, case_%d);@\n" label i)
    accepted;
  Fmt.pf ppf "  ]@\n@\nlet refused : (string * string) list =@\n  [@\n";
  List.iter
    (fun (label, msg) -> Fmt.pf ppf "    (%S, %S);@\n" label msg)
    refused;
  Fmt.pf ppf "  ]@."
