(* Writes a module generated by [Wire_ocaml] for every codec of
   [Diff_ocaml.codecs] it accepts, under the interface [Wire_ocaml] writes for
   it, each wrapped in the glue that hands its functions to [Diff_ocaml] under
   one type, and the codecs it refused with its reason; then the scanners. The
   first file named on the command line is the index, which lists them; the
   others are the shards that define them, each compiled on its own. [--oxcaml]
   generates for the OxCaml target. *)

open Wire.Private
module T = Types

let target =
  if Array.exists (String.equal "--oxcaml") Sys.argv then `OxCaml else `OCaml

type field = {
  name : string;
  plain : string;  (** The show of its value. *)
  acc : string;  (** Its accessor in the module's views. *)
}

(* The accessors of the views of [c], one per field of its fixed record, in
   the order of its fields. *)
let accessors c =
  List.map
    (function
      | Wire_ocaml.Int { name; _ }
      | Bool { name; _ }
      | Record { name; _ }
      | Bytes { name; _ } ->
          name)
    (Wire_ocaml.views c).members

let fields c =
  let accs = accessors c in
  List.mapi
    (fun i (T.Field f) ->
      let name = Option.get f.field_name in
      let acc =
        match List.nth_opt accs i with
        | Some a -> a
        | None -> Fmt.failwith "gen: field %s has no accessor" name
      in
      let plain =
        match Diff_ocaml.show_code f.field_typ with
        | Some s -> s
        | None ->
            Fmt.failwith "gen: field %s has a type the backend cannot show" name
      in
      { name; plain; acc })
    (Gen.to_struct c).fields

(* A read of the view [v] of [bb] through the module's accessor of [f]. *)
let pp_access ppf f = Fmt.pf ppf "%s (M.%s bb v)" f.plain f.acc

(* The glue over [M]: its decoder, validator and encoder, and its views,
   [check], [is_ok], [get] and an accessor per field. *)
let pp_ops ppf fields =
  Fmt.pf ppf
    "{@\n\
    \      Diff_ocaml.decode =@\n\
    \        (fun b o ->@\n\
    \          Result.map (fun r ->@\n\
    \              let out = Bytes.create M.min_size in@\n\
    \              M.encode r out ~off:0;@\n\
    \              Bytes.to_string out)@\n\
    \            (M.decode b ~off:o));@\n\
    \      validate = (fun b o -> M.validate b ~off:o);@\n\
    \      encode =@\n\
    \        (fun s b o ->@\n\
    \          let r = Result.get_ok (M.decode (Bytes.of_string s) ~off:0) in@\n\
    \          M.encode r b ~off:o);@\n\
    \      reads = [ %a ];@\n\
    \      valid =@\n\
    \        (fun b ->@\n\
    \          Result.map (fun () ->@\n\
    \              match Wire_runtime.Buf.v b with@\n\
    \              | Wire_runtime.Buf.Any bb ->@\n\
    \                  let v = M.get (M.check bb ~off:0) in@\n\
    \                  [ %a ])@\n\
    \            (M.validate b ~off:0));@\n\
    \      view =@\n\
    \        (fun b o ->@\n\
    \          Result.map (fun () ->@\n\
    \              match Wire_runtime.Buf.v b with@\n\
    \              | Wire_runtime.Buf.Any bb ->@\n\
    \                  let v = M.get (M.check bb ~off:o) in@\n\
    \                  [ %a ])@\n\
    \            (M.validate b ~off:o));@\n\
    \      checked =@\n\
    \        (fun b o ->@\n\
    \          match Wire_runtime.Buf.v b with@\n\
    \          | Wire_runtime.Buf.Any bb ->@\n\
    \              let c = M.check bb ~off:o in@\n\
    \              if M.is_ok c then@\n\
    \                let v = M.get c in@\n\
    \                (true, [ %a ])@\n\
    \              else (false, []));@\n\
    \    }"
    Fmt.(list ~sep:(any "; ") (fun ppf f -> pf ppf "%S" f.name))
    fields
    Fmt.(list ~sep:(any "; ") pp_access)
    fields
    Fmt.(list ~sep:(any "; ") pp_access)
    fields
    Fmt.(list ~sep:(any "; ") pp_access)
    fields

(* The module generated from [c] under its interface. *)
let pp_case ppf (label, c, (src, intf)) =
  Fmt.pf ppf
    "let %s : Fuzz_gen.packed -> Diff_ocaml.t = function@\n\
    \  | Fuzz_gen.Pack _ ->@\n\
    \  let module M : sig@\n\
     %s@\n\
    \  end = struct@\n\
     %s@\n\
    \  end in@\n\
    \  %a@\n\
     @\n"
    label intf src pp_ops (fields c)

(* {1 Scanners}

   Each scanner is a module generated with a fold of some of the codec's
   integer fields, named by their paths ({!Fold_paths}), handed to
   [Diff_ocaml] through that fold: on one frame of an index, in the slots of
   a stride over a frame, and over an index. Its [f] conses each record's
   fields onto the accumulator as the outputs the references name, an absent
   field 0, with its own presence where it has one. A structured case gets
   the module of every field, one of every other field, one of none, and on
   OxCaml one for the default target too; a sampled shape the first two. *)

(* The value of [l], bound to [x], as the outputs it gives. *)
let leaf_outputs (l : Fold_paths.leaf) x =
  let conv =
    match l.carrier with Some m -> m ^ ".to_int" | None -> "Fun.id"
  in
  let some v = Fmt.str "(%S, %s %s)" l.output conv v
  and zero = Fmt.str "(%S, 0)" l.output in
  let present n = Option.map (fun p -> Fmt.str "(%S, %d)" p n) l.own in
  let list xs = "[ " ^ String.concat "; " xs ^ " ]" in
  let yes = list (some "x" :: Option.to_list (present 1))
  and no = list (zero :: Option.to_list (present 0)) in
  match (Option.is_some l.own, l.layered) with
  | false, false -> list [ some x ]
  | true, false | false, true ->
      Fmt.str "(match %s with Some x -> %s | None -> %s)" x yes no
  | true, true ->
      Fmt.str "(match %s with Some (Some x) -> %s | _ -> %s)" x yes no

(* The visitor of the fold of [ls]: it conses each record's outputs onto the
   accumulator. *)
let pp_visitor ppf ls =
  let xs = List.mapi (fun i l -> (l, Fmt.str "x%d" i)) ls in
  Fmt.pf ppf "(fun acc%s -> Some (List.concat [ %s ]) :: acc)"
    (String.concat ""
       (List.map
          (fun ((l : Fold_paths.leaf), x) -> Fmt.str " ~%s:%s" l.label x)
          xs))
    (String.concat "; " (List.map (fun (l, x) -> leaf_outputs l x) xs))

(* The scanner of the module [m], whose fold hands out [ls]: one frame of an
   index, the slots of a stride over a frame, and an index. *)
let pp_backend ppf ~m ls =
  Fmt.pf ppf
    "(let f = %a and invalid acc = None :: acc in@\n\
     { Diff_ocaml.scan_name = %S; scan_fields = [%a];@\n\
     scan = (fun b o n -> match %s.fold b ~offs:[| o |] ~lens:[| n |] ~invalid \
     ~init:[] ~f with Ok [ v ] -> v | _ -> failwith \"fold\");@\n\
     scan_batch = Some (fun b o n stride -> if o < 0 || n < 0 || o > \
     Bytes.length b - n || stride <= 0 then None else match %s.fold (Bytes.sub \
     b o n) ~stride ~invalid ~init:[] ~f with Ok l -> Some (List.rev l) | \
     Error _ -> None);@\n\
     scan_index = Some (fun b offs lens -> match %s.fold b ~offs ~lens \
     ~invalid ~init:[] ~f with Ok l -> List.rev l | Error _ -> failwith \
     \"index\") });@\n"
    pp_visitor ls m
    Fmt.(list ~sep:(any "; ") (fun ppf n -> pf ppf "%S" n))
    (Fold_paths.outputs ls) m m m

(* [fold] of the module [m] of [ls] on one frame, its outputs. *)
let pp_full ~m ppf ls =
  Fmt.pf ppf
    "(fun b o n -> match %s.fold b ~offs:[| o |] ~lens:[| n |] ~invalid:(fun \
     acc -> None :: acc) ~init:[] ~f:%a with Ok [ v ] -> v | _ -> failwith \
     \"fold\")"
    m pp_visitor ls

(* The outputs of [view], each [fill]. *)
let rec view_zeros ~fill (view : Wire_ocaml.view) =
  Fmt.str "List.concat [%s]"
    (String.concat "; "
       (List.map
          (function
            | Wire_ocaml.Int { output; _ } | Bool { output; _ } ->
                Fmt.str "[ (%S, %s) ]" output fill
            | Bytes _ -> "[]"
            | Record { presence; view; _ } ->
                (match presence with
                  | Some p -> Fmt.str "[ (%S, %s) ]" p fill ^ " @ "
                  | None -> "")
                ^ view_zeros ~fill view)
          view.members))

(* The outputs the views of [view] hand out, in the module [path] of the
   scanner [m], from the view [v] of [bb]: a record that is absent hands out
   0 for each of its outputs, and a mandatory one whose check fails
   [min_int], which no reference states. *)
let rec view_outputs ~m ~path (view : Wire_ocaml.view) =
  Fmt.str "(List.concat [%s])"
    (String.concat "; " (List.map (view_member ~m ~path) view.members))

and view_member ~m ~path = function
  | Wire_ocaml.Int { name; output; carrier } ->
      Fmt.str "[ (%S, %s (%s.%s bb v)) ]" output
        (match carrier with Some m -> m ^ ".to_int" | None -> "Fun.id")
        path name
  | Bytes _ -> "[]"
  | Bool { name; output } ->
      Fmt.str "[ (%S, Bool.to_int (%s.%s bb v)) ]" output path name
  | Record { name; presence; view } ->
      let sub = m ^ "." ^ Option.get view.module_name in
      let presence_is n =
        match presence with
        | Some p -> Fmt.str "[ (%S, %d) ]" p n ^ " @ "
        | None -> ""
      in
      let fill = if Option.is_none presence then "min_int" else "0" in
      Fmt.str
        "(let k = %s.%s bb v in if %s.is_ok k then (let v = %s.get k in %s%s) \
         else %s%s)"
        path name sub sub (presence_is 1)
        (view_outputs ~m ~path:sub view)
        (presence_is 0) (view_zeros ~fill view)

(* The backend of the views of the module [m], which hands out every output,
   checked against [m]'s fold of [ls] and against the codec [codec]. *)
let pp_view_backend ppf ~m ~codec ~ls c =
  let fields = Wire_ocaml.outputs c in
  let wrap, codec = codec in
  (* A codec of constant size is checked at an offset, as Codec.View checks
     it: on the frame's own bytes. *)
  let frame, check =
    match Wire.Codec.fixed_size c with
    | None -> ("", Fmt.str "%s.check bb ~off:o ~len:n" m)
    | Some _ ->
        ( "if o < 0 || n < 0 || n > Bytes.length b - o then None else let b = \
           Bytes.sub b o n in ",
          Fmt.str "%s.check bb ~off:0" m )
  in
  Fmt.pf ppf
    "%s Diff_ocaml.view_scan ~name:%S ~codec:%s ~fields:[%a] ~full:%a (fun b o \
     n -> %smatch Wire_runtime.Buf.v b with Wire_runtime.Buf.Any bb -> let c = \
     %s in if %s.is_ok c then (let %s = %s.get c in Some %s) else None));@\n"
    wrap (m ^ " views") codec
    Fmt.(list ~sep:(any "; ") (fun ppf (n, _) -> pf ppf "%S" n))
    fields (pp_full ~m) ls frame check m
    (if
       List.for_all
         (function Wire_ocaml.Bytes _ -> true | _ -> false)
         (Wire_ocaml.views c).members
     then "_"
     else "v")
    m
    (view_outputs ~m ~path:m (Wire_ocaml.views c))

(* Whether the module holds a fixed record's members, which the record
   glue reads: its [encode] is its [write]. Without them its values go through
   the walk. *)
let has_record src =
  let sub = " ~off = write buf ~off " in
  let n = String.length sub in
  let rec go i =
    i + n <= String.length src
    && (String.equal (String.sub src i n) sub || go (i + 1))
  in
  go 0

(* The backend of the values of the module [m], when its codec's record holds
   more than named scalars at constant offsets. *)
let pp_values_backend ppf ~m ~codec ~ls c =
  if not (has_record Wire_ocaml.(to_ml (v ~target:`OCaml c))) then begin
    let wrap, codec = codec in
    Fmt.pf ppf
      "%s Diff_ocaml.values_scan ~name:%S ~codec:%s ~fields:[%a] ~full:%a { \
       Diff_ocaml.decode = (fun b o -> match %s.decode b ~off:o with Error e \
       -> Error e | Ok r -> let out = Bytes.create (%s.size r) in %s.encode r \
       out ~off:0; Ok (Bytes.to_string out)); validate = (fun b o -> \
       %s.validate b ~off:o) });@\n"
      wrap (m ^ " values") codec
      Fmt.(list ~sep:(any "; ") (fun ppf n -> pf ppf "%S" n))
      (Fold_paths.outputs ls) (pp_full ~m) ls m m m m
  end

(* The fields of [c] the module for [target] folds: every one, or those of
   the paths [selected], each kept where the generator takes it. *)
let fold_leaves target c selected =
  let all = Fold_paths.leaves c in
  let wanted =
    match selected with
    | None -> all
    | Some paths ->
        List.filter (fun (l : Fold_paths.leaf) -> List.mem l.path paths) all
  in
  Fold_paths.accepted (fun fold -> Wire_ocaml.v ~target ~fold c) wanted

(* The scanner modules over [c], each a suffix of its value's name, whether
   its backends read [c] and the expression of its backends: each module
   [(name, target, selected)] generated inside the expression under its
   interface, with the views and values of the one with every field. [codec]
   spells [c] for the backends that read it. *)
let scanners ~codec c modules =
  List.map
    (fun (m, t, selected) ->
      let ls = fold_leaves t c selected in
      let g =
        Wire_ocaml.v ~target:t
          ~fold:(List.map (fun (l : Fold_paths.leaf) -> l.path) ls)
          c
      in
      let pp ppf () =
        Fmt.pf ppf
          "let module %s : sig@\n%s@\nend = struct@\n%s@\nend in@\n[@\n" m
          (Wire_ocaml.to_mli g) (Wire_ocaml.to_ml g);
        pp_backend ppf ~m ls;
        if selected = None then begin
          pp_view_backend ppf ~m ~codec ~ls c;
          pp_values_backend ppf ~m ~codec ~ls c
        end;
        Fmt.pf ppf "]@\n"
      in
      (String.lowercase_ascii m, selected = None, pp))
    modules

let every_other c =
  List.map
    (fun (l : Fold_paths.leaf) -> l.path)
    (Fold_paths.every_other (Fold_paths.leaves c))

(* {1 Shards}

   Each case, and each scanner module of a structured or sampled scanner, is a
   top-level value of one of the shards, and the index lists them in order.
   The shards are balanced by size so that no compiler run has to hold all of
   them. A scanner's modules are separate values, so that the largest value,
   which a shard cannot split, is one module and not all of them: the
   compiler's peak heap follows the largest functions it allocates registers
   for more than the size of the file. *)

type def = { name : string; src : string }

(* The definition of each scanner module of [c], named after [prefix] and the
   module, whose head is [head]: told whether the module's backends read
   [codec]. *)
let scanner_defs ~prefix ~head ~codec c modules =
  List.map
    (fun (suffix, reads_codec, pp) ->
      let name = Fmt.str "%s_%s" prefix suffix in
      let src = Fmt.str "%a%a@\n" head (name, reads_codec) pp () in
      { name; src })
    (scanners ~codec c modules)

let scan_cases () =
  List.mapi
    (fun i (Diff_codecs.Scan c) ->
      let modules =
        [
          ("Full", target, None);
          ("Selected", target, Some (every_other c.codec));
          ("Checks", target, Some []);
        ]
        @ if target = `OxCaml then [ ("Stock", `OCaml, None) ] else []
      in
      ( c.label,
        scanner_defs ~prefix:(Fmt.str "scan_case_%d" i)
          ~head:(fun ppf (name, _) ->
            Fmt.pf ppf "let %s () : Diff_ocaml.scan_ops list =@\n" name)
          ~codec:
            ( Fmt.str
                "(match List.nth Diff_codecs.scan_cases %d with \
                 Diff_codecs.Scan sc ->"
                i,
              "sc.codec" )
          c.codec modules ))
    Diff_codecs.scan_cases

let sampled_scanners () =
  let accepted, refused =
    List.partition_map
      (fun (label, (Fuzz_gen.Pack g as p)) ->
        let c = Fuzz_gen.codec g in
        match Wire_ocaml.outputs c with
        | _ -> Left (label, p)
        | exception Invalid_argument msg -> Right (label, msg))
      Diff_ocaml.scan_codecs
  in
  let accepted =
    List.mapi
      (fun i (label, Fuzz_gen.Pack g) ->
        let c = Fuzz_gen.codec g in
        ( label,
          scanner_defs ~prefix:(Fmt.str "sampled_%d" i)
            ~head:(fun ppf (name, reads_codec) ->
              Fmt.pf ppf
                "let %s : Fuzz_gen.packed -> Diff_ocaml.scan_ops list = \
                 function@\n\
                \  | Fuzz_gen.Pack %s ->@\n"
                name
                (if reads_codec then "g" else "_"))
            ~codec:("(", "(Fuzz_gen.codec g)")
            c
            [
              ("Full", target, None); ("Selected", target, Some (every_other c));
            ] ))
      accepted
  in
  (accepted, refused)

let cases () =
  let accepted, refused =
    List.partition_map
      (fun (label, Fuzz_gen.Pack g) ->
        let c = Fuzz_gen.codec g in
        match Wire_ocaml.to_ml (Wire_ocaml.v ~target c) with
        | src when has_record src ->
            let intf = Wire_ocaml.to_mli (Wire_ocaml.v ~target c) in
            Left (label, Fuzz_gen.Pack g, (src, intf))
        | _ when Diff_ocaml.specialisable c ->
            Right
              (label, "a fixed record whose members would define a name twice")
        | _ -> Right (label, "no fixed record: its values go through the walk")
        | exception Invalid_argument msg -> Right (label, msg))
      Diff_ocaml.codecs
  in
  let accepted =
    List.mapi
      (fun i (label, Fuzz_gen.Pack g, src) ->
        let name = Fmt.str "case_%d" i in
        let src = Fmt.str "%a" pp_case (name, Fuzz_gen.codec g, src) in
        (label, { name; src }))
      accepted
  in
  (accepted, refused)

(* The shard of each of [defs], out of [n]: the largest first, each to the
   lightest shard so far. *)
let assign n defs =
  let load = Array.make n 0 in
  let owner = Hashtbl.create 64 in
  let lightest () =
    let k = ref 0 in
    Array.iteri (fun i l -> if l < load.(!k) then k := i) load;
    !k
  in
  let size d = String.length d.src in
  List.stable_sort (fun a b -> Int.compare (size b) (size a)) defs
  |> List.iter (fun d ->
      let k = lightest () in
      load.(k) <- load.(k) + size d;
      Hashtbl.replace owner d.name k);
  Hashtbl.find owner

let module_name file =
  String.capitalize_ascii (Filename.remove_extension (Filename.basename file))

let header =
  "(* Generated by test/diff/gen_ocaml.exe from the codecs of \
   Diff_ocaml.codecs. *)\n\n"

let write_shard file defs =
  Out_channel.with_open_text file (fun oc ->
      output_string oc header;
      output_string oc
        "(* Each case binds its module locally and uses only part of it: some \
         of its\n\
        \   values, types and record fields go unused. *)\n\
         [@@@warning \"-32-34-69\"]\n\n";
      List.iter (fun d -> output_string oc d.src) defs)

let pp_entries ~typ ~qualify ppf (name, entries) =
  Fmt.pf ppf "let %s : (string * %s) list =@\n  [@\n" name typ;
  List.iter
    (fun (label, v) -> Fmt.pf ppf "    (%S, %s);@\n" label (qualify v))
    entries;
  Fmt.pf ppf "  ]@\n@\n"

(* A scanner's modules, in [qualify]'d names, as one function of [arg]. *)
let joined ~qualify ~arg defs =
  Fmt.str "(fun %s -> List.concat [ %s ])" arg
    (String.concat "; " (List.map (fun d -> qualify d ^ " " ^ arg) defs))

let write_index file ~qualify ~cases ~refused ~scans ~sampled ~scan_refused =
  Out_channel.with_open_text file (fun oc ->
      let ppf = Format.formatter_of_out_channel oc in
      let msgs = pp_entries ~qualify:(Fmt.str "%S") ~typ:"string" in
      Fmt.pf ppf "%slet name = %S@\n@\n" header
        (match target with `OCaml -> "ocaml" | `OxCaml -> "oxcaml");
      pp_entries ~qualify ~typ:"(Fuzz_gen.packed -> Diff_ocaml.t)" ppf
        ("covered", cases);
      msgs ppf ("refused", refused);
      pp_entries
        ~qualify:(joined ~qualify ~arg:"()")
        ~typ:"(unit -> Diff_ocaml.scan_ops list)" ppf ("scanners", scans);
      pp_entries ~qualify:(joined ~qualify ~arg:"p")
        ~typ:"(Fuzz_gen.packed -> Diff_ocaml.scan_ops list)" ppf
        ("sampled_scanners", sampled);
      msgs ppf ("scan_refused", scan_refused);
      Format.pp_print_flush ppf ())

let usage () =
  Fmt.epr "usage: %s [--oxcaml] INDEX.ml SHARD.ml...@." Sys.argv.(0);
  exit 2

(* Writes the index to the first file and the shards to the others. *)
let () =
  match List.filter (( <> ) "--oxcaml") (List.tl (Array.to_list Sys.argv)) with
  | [] | [ _ ] -> usage ()
  | index :: shards ->
      let cases, refused = cases () in
      let scans = scan_cases () in
      let sampled, scan_refused = sampled_scanners () in
      let all = List.map snd cases @ List.concat_map snd (scans @ sampled) in
      let shards = Array.of_list shards in
      let owner = assign (Array.length shards) all in
      Array.iteri
        (fun k file ->
          write_shard file (List.filter (fun d -> owner d.name = k) all))
        shards;
      let qualify d = module_name shards.(owner d.name) ^ "." ^ d.name in
      write_index index ~qualify ~cases ~refused ~scans ~sampled ~scan_refused
