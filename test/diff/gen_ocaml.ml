(* Writes [ocaml_index.ml]: a module generated by [Wire_ocaml] for every codec
   of [Diff_ocaml.codecs] it accepts, each wrapped in the glue that hands
   its functions to [Diff_ocaml] under one type, and the codecs it refused with
   its reason. [--oxcaml] generates for the OxCaml target. *)

open Wire.Private
module T = Types

let target =
  if Array.exists (String.equal "--oxcaml") Sys.argv then `OxCaml else `OCaml

type field = {
  name : string;
  ident : string;
  show : string;
  views : Diff_ocaml.view list;
}

let fields c =
  List.map
    (fun (T.Field f) ->
      let name = Option.get f.field_name in
      let show =
        match Diff_ocaml.show_code f.field_typ with
        | Some s -> s
        | None ->
            Fmt.failwith "gen: field %s has a type the backend cannot show" name
      in
      {
        name;
        ident = Wire_ocaml.ident name;
        show;
        views = Diff_ocaml.views f.field_typ;
      })
    (Gen.to_struct c).fields

let view = function
  | Diff_ocaml.Get -> "Diff_ocaml.Get"
  | Get_int -> "Diff_ocaml.Get_int"
  | Of_word -> "Diff_ocaml.Of_word"

(* Each getter of [f] in module [m], on the buffer [buf] makes from [b]. *)
let pp_gets ~m ~buf ppf f =
  List.iter
    (fun v ->
      let read =
        match v with
        | Diff_ocaml.Get -> Fmt.str "%s (%s.get_%s (%s) o)" f.show m f.ident buf
        | Get_int ->
            Fmt.str "string_of_int (%s.get_%s_int (%s) o)" m f.ident buf
        | Of_word ->
            Fmt.str "string_of_int (%s.%s_of_word (%s.get_%s_word (%s) o))" m
              f.ident m f.ident buf
      in
      Fmt.pf ppf "        (%S, %s, fun b o -> %s);@\n" f.name (view v) read)
    f.views

(* The reads after [Valid.v]: a [read_<f>] for every field, and a
   [read_<f>_int] for a 32-bit one. *)
let reads fields =
  List.concat_map
    (fun f ->
      List.filter_map
        (function
          | Diff_ocaml.Get -> Some (f, Diff_ocaml.Get)
          | Get_int -> Some (f, Get_int)
          | Of_word -> None)
        f.views)
    fields

let pp_read ?(prefix = "read") ~m ppf (f, v) =
  match v with
  | Diff_ocaml.Get -> Fmt.pf ppf "%s (%s.%s_%s v)" f.show m prefix f.ident
  | _ -> Fmt.pf ppf "string_of_int (%s.%s_%s_int v)" m prefix f.ident

(* The glue over [m] ("M" or "M.Bigstring"), whose buffer [buf] makes from
   the bytes [b]; [back] wraps a write so its bytes land in [b]. *)
let pp_ops ppf ~m ~buf ~back fields =
  let reads = reads fields in
  Fmt.pf ppf
    "{@\n\
    \      Diff_ocaml.decode =@\n\
    \        (fun b o ->@\n\
    \          let out = Bytes.create M.size in@\n\
    \          M.encode (%s.decode (%s) o) out 0;@\n\
    \          Bytes.to_string out);@\n\
    \      validate = (fun b o -> %s.validate (%s) o);@\n\
    \      encode =@\n\
    \        (fun s b o ->@\n\
    \          let r = M.decode (Bytes.of_string s) 0 in@\n\
    \          %a);@\n\
    \      gets = [@\n\
     %a      ];@\n\
    \      reads = [ %a ];@\n\
    \      valid = (fun b -> let v = %s.Valid.v (%s) in [ %a ]);@\n\
    \      is_valid = (fun b o -> %s.is_valid (%s) o);@\n\
    \      view = (fun b o -> let v = %s.View.at (%s) o in [ %a ]);@\n\
    \      checked =@\n\
    \        (fun b o ->@\n\
    \          let v = %s.View.check (%s) o in@\n\
    \          (%s.View.ok v, [ %a ]));@\n\
    \    }"
    m buf m buf back (Fmt.str "%s.encode r" m)
    Fmt.(list ~sep:nop (pp_gets ~m ~buf))
    fields
    Fmt.(
      list ~sep:(any "; ") (fun ppf (f, v) -> pf ppf "(%S, %s)" f.name (view v)))
    reads m buf
    Fmt.(list ~sep:(any "; ") (pp_read ~m))
    reads m buf m buf
    Fmt.(list ~sep:(any "; ") (pp_read ~prefix:"view" ~m))
    reads m buf m
    Fmt.(list ~sep:(any "; ") (pp_read ~prefix:"view" ~m))
    reads

(* The module generated from [c], and its bridge, which checks it against
   the codec. *)
let pp_case ppf (label, c, src) =
  let fields = fields c in
  Fmt.pf ppf
    "let %s : Fuzz_gen.packed -> Diff_ocaml.t = function@\n\
    \  | Fuzz_gen.Pack g ->@\n\
    \  let codec = Fuzz_gen.codec g in@\n\
    \  let module M = struct@\n\
     %s@\n\
    \  end in@\n\
    \  let module B = struct@\n\
     %s@\n\
    \  end in@\n\
    \  {@\n\
    \    Diff_ocaml.bytes =@\n\
    \      %a;@\n\
    \    bigstring =@\n\
    \      %a;@\n\
    \  }@\n\
     @\n"
    label src
    (Wire_ocaml.bridge ~codec:"codec" ~core:"M" c)
    (pp_ops ~m:"M" ~buf:"b" ~back:(fun ppf w -> Fmt.pf ppf "%s b o" w))
    fields
    (pp_ops ~m:"M.Bigstring" ~buf:"Diff_ocaml.big b" ~back:(fun ppf w ->
         Fmt.pf ppf
           "let bb = Diff_ocaml.big b in %s bb o; Diff_ocaml.blit_back bb b" w))
    fields

(* {1 Scanners}

   Each scanner is handed to [Diff_ocaml] as its [decode] and [fold_frames],
   on OxCaml also as their unboxed forms. A structured case gets the scanner
   of every output, one of every other output, one of none, and on OxCaml one
   for the default target too; a sampled shape the first two. *)

let snapshot ppf ~unboxed ~var fields =
  Fmt.pf ppf "[";
  List.iter
    (fun (n, is_bool) ->
      let v = var n in
      Fmt.pf ppf "(%S, %s);" n
        (if is_bool then "(if " ^ v ^ " then 1 else 0)"
         else if unboxed then "(Wire_runtime.Target.Int64_u.to_int " ^ v ^ ")"
         else v))
    fields;
  Fmt.pf ppf "]"

let pp_backend ppf ~m ~unboxed fields =
  let args =
    if fields = [] then "()"
    else
      String.concat " "
        (List.map (fun (n, _) -> "~" ^ n ^ ":field_" ^ n) fields)
  in
  let values ppf () =
    snapshot ppf ~unboxed ~var:(fun n -> "field_" ^ n) fields
  in
  let batch ppf () =
    if unboxed then
      Fmt.pf ppf
        "Some (fun b o n stride -> let results = ref [] in try let _ = \
         %s.fold_frames_unboxed b o n ~stride ~init:#0L ~invalid:(fun acc -> \
         results := None :: !results; acc) ~valid:(fun acc %s -> results := \
         Some %a :: !results; acc) in Some (List.rev !results) with \
         Invalid_argument _ -> None)"
        m args values ()
    else
      Fmt.pf ppf
        "Some (fun b o n stride -> try Some (List.rev (%s.fold_frames b o n \
         ~stride ~init:[] ~invalid:(fun acc -> None :: acc) ~valid:(fun acc %s \
         -> Some %a :: acc))) with Invalid_argument _ -> None)"
        m args values ()
  in
  Fmt.pf ppf
    "{ Diff_ocaml.scan_name = %S; scan_fields = [%a]; scan = (fun b o n -> let \
     v = %s.%s b o n in if v.%sok then Some %a else None); scan_batch = %a };@\n"
    (m ^ if unboxed then " unboxed" else "")
    Fmt.(list ~sep:(any "; ") (fun ppf (n, _) -> pf ppf "%S" n))
    fields m
    (if unboxed then "decode_unboxed" else "decode")
    (if unboxed then "#" else "")
    (fun ppf () ->
      snapshot ppf ~unboxed
        ~var:(fun n -> "v." ^ (if unboxed then "#" else "") ^ n)
        fields)
    () batch ()

(* The backends over [c]: each module [(name, target, selected)], generated
   inside the function. *)
let pp_scanners ppf ~label c modules =
  let fields = Wire_ocaml.scanner_fields c in
  List.iter
    (fun (m, t, selected) ->
      Fmt.pf ppf "let module %s = struct@\n%s@\nend in@\n" m
        (Wire_ocaml.scanner ~target:t ?fields:selected ~codec:label c))
    modules;
  Fmt.pf ppf "[@\n";
  List.iter
    (fun (m, t, selected) ->
      let fields =
        match selected with
        | None -> fields
        | Some ns -> List.filter (fun (n, _) -> List.mem n ns) fields
      in
      pp_backend ppf ~m ~unboxed:false fields;
      if t = `OxCaml then pp_backend ppf ~m ~unboxed:true fields)
    modules;
  Fmt.pf ppf "]@\n"

let every_other c =
  List.filteri (fun i _ -> i mod 2 = 0) (Wire_ocaml.scanner_fields c)
  |> List.map fst

let pp_scan_cases ppf =
  List.iteri
    (fun i (Diff_codecs.Scan c) ->
      Fmt.pf ppf "let scan_case_%d () : Diff_ocaml.scan_ops list =@\n" i;
      pp_scanners ppf ~label:c.label c.codec
        ([
           ("Full", target, None);
           ("Selected", target, Some (every_other c.codec));
           ("Checks", target, Some []);
         ]
        @ if target = `OxCaml then [ ("Stock", `OCaml, None) ] else []);
      Fmt.pf ppf "@\n")
    Diff_codecs.scan_cases;
  Fmt.pf ppf "let scanners = [@\n";
  List.iteri
    (fun i (Diff_codecs.Scan c) ->
      Fmt.pf ppf "  (%S, scan_case_%d);@\n" c.label i)
    Diff_codecs.scan_cases;
  Fmt.pf ppf "]@\n@\n"

let pp_sampled_scanners ppf =
  let accepted, refused =
    List.partition_map
      (fun (label, (Fuzz_gen.Pack g as p)) ->
        let c = Fuzz_gen.codec g in
        match Wire_ocaml.scanner_fields c with
        | _ -> Left (label, p)
        | exception Invalid_argument msg -> Right (label, msg))
      Diff_ocaml.scan_codecs
  in
  List.iteri
    (fun i (_, Fuzz_gen.Pack g) ->
      let c = Fuzz_gen.codec g in
      Fmt.pf ppf
        "let sampled_%d : Fuzz_gen.packed -> Diff_ocaml.scan_ops list = \
         function@\n\
        \  | Fuzz_gen.Pack _ ->@\n"
        i;
      pp_scanners ppf ~label:"codec" c
        [ ("Full", target, None); ("Selected", target, Some (every_other c)) ];
      Fmt.pf ppf "@\n")
    accepted;
  Fmt.pf ppf
    "let sampled_scanners : (string * (Fuzz_gen.packed -> Diff_ocaml.scan_ops \
     list)) list = [@\n";
  List.iteri
    (fun i (label, _) -> Fmt.pf ppf "  (%S, sampled_%d);@\n" label i)
    accepted;
  Fmt.pf ppf "]@\n@\nlet scan_refused : (string * string) list = [@\n";
  List.iter (fun (label, msg) -> Fmt.pf ppf "  (%S, %S);@\n" label msg) refused;
  Fmt.pf ppf "]@."

let () =
  let ppf = Format.std_formatter in
  let accepted, refused =
    List.partition_map
      (fun (label, Fuzz_gen.Pack g) ->
        let c = Fuzz_gen.codec g in
        match Wire_ocaml.ml ~target ~codec:"codec" c with
        | src -> Left (label, Fuzz_gen.Pack g, src)
        | exception Invalid_argument msg -> Right (label, msg))
      Diff_ocaml.codecs
  in
  Fmt.pf ppf
    "(* Generated by test/diff/gen_ocaml.exe from the codecs of \
     Diff_ocaml.codecs. *)@\n\
     @\n";
  Fmt.pf ppf "let name = %S@\n@\n"
    (match target with `OCaml -> "ocaml" | `OxCaml -> "oxcaml");
  List.iteri
    (fun i (_, Fuzz_gen.Pack g, src) ->
      pp_case ppf (Fmt.str "case_%d" i, Fuzz_gen.codec g, src))
    accepted;
  Fmt.pf ppf
    "let covered : (string * (Fuzz_gen.packed -> Diff_ocaml.t)) list =@\n  [@\n";
  List.iteri
    (fun i (label, _, _) -> Fmt.pf ppf "    (%S, case_%d);@\n" label i)
    accepted;
  Fmt.pf ppf "  ]@\n@\nlet refused : (string * string) list =@\n  [@\n";
  List.iter
    (fun (label, msg) -> Fmt.pf ppf "    (%S, %S);@\n" label msg)
    refused;
  Fmt.pf ppf "  ]@\n@\n";
  pp_scan_cases ppf;
  pp_sampled_scanners ppf
