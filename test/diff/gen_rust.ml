(* Writes the Rust backend of the differential fuzzer into the directory given
   as the first argument: a module generated by [Wire_rust] for every codec of
   [Diff_ocaml.codecs] it accepts, the scanners [Wire_rust.scanner] generates
   for each structured case of [Diff_codecs.scan_cases], for scanned schemas
   of test/ocaml and for each sampled shape of
   [Diff_ocaml.scan_codecs], and [lib.rs], which compiles them into one
   [no_std] static library whose C entry points, [wire_rs_call] and
   [wire_rs_scan], run one operation of one codec's module and one scanner.
   Writes [rust_index.ml] in the current directory: each accepted codec's case
   number and fields, the codecs refused with the reason, and each scanner's
   number and outputs. *)

open Wire.Private
module T = Types

type field = { name : string; ident : string; kind : string }

let rec kind : type a. a T.typ -> string = function
  | T.Bits _ -> "Diff_rust.Bits"
  | T.Byte_array { size = T.Int n } -> Fmt.str "(Diff_rust.Bytes %d)" n
  | T.Where { inner; _ } -> kind inner
  | T.Enum { base; _ } -> kind base
  | _ -> "Diff_rust.Int"

let fields c =
  List.map
    (fun (T.Field f) ->
      let name = Option.get f.field_name in
      { name; ident = Wire_rust.ident name; kind = kind f.field_typ })
    (Gen.to_struct c).fields

let write file s =
  let oc = open_out_bin file in
  output_string oc s;
  close_out oc

(* A Rust string literal, for a field name the generated module accepted, so
   one that is UTF-8. *)
let rust_string s =
  let b = Buffer.create (String.length s + 2) in
  Buffer.add_char b '"';
  String.iter
    (function
      | '"' -> Buffer.add_string b "\\\""
      | '\\' -> Buffer.add_string b "\\\\"
      | c when Char.code c < 0x20 || Char.code c = 0x7f ->
          let hex = "0123456789abcdef" in
          Buffer.add_string b "\\x";
          Buffer.add_char b hex.[Char.code c lsr 4];
          Buffer.add_char b hex.[Char.code c land 0xf]
      | c -> Buffer.add_char b c)
    s;
  Buffer.add_char b '"';
  Buffer.contents b

let prelude =
  {|// Generated by test/diff/gen_rust.exe. The C entry point of the Rust
// backend of the differential fuzzer.

#![no_std]
#![allow(unused_variables, unreachable_patterns)]

extern "C" {
    fn abort() -> !;
}

#[panic_handler]
fn panic(_: &core::panic::PanicInfo) -> ! {
    unsafe { abort() }
}

// The prebuilt [core] unwinds, so it names a personality routine; with
// panics that abort, nothing ever calls it.
#[no_mangle]
extern "C" fn rust_eh_personality() {}

// The outcome codes [Diff_rust] reads: 0 is success, the others an error,
// whose offset, value and field number go in [res].
macro_rules! error {
    ($m:ident, $index:ident) => {
        fn err(e: $m::Error, res: &mut [i64]) -> i32 {
            match e {
                $m::Error::TooShort { expected, got } => {
                    res[0] = expected as i64;
                    res[1] = got as i64;
                    1
                }
                $m::Error::Constraint { field, at } => {
                    res[0] = at as i64;
                    res[2] = $index(field);
                    2
                }
                $m::Error::InvalidEnum { field, at, value } => {
                    res[0] = at as i64;
                    res[1] = value;
                    res[2] = $index(field);
                    3
                }
                $m::Error::Overflow => 4,
                $m::Error::OutOfRange { field, value } => {
                    res[1] = value;
                    res[2] = $index(field);
                    5
                }
            }
        }
    };
}
|}

(* The value of field [f] of the record [r], as a write takes it. *)
let arg f = if f.kind.[0] = '(' then "&r." ^ f.ident else "r." ^ f.ident

(* How [put] hands a getter's value back: an integer in [res], bytes in
   [out]. *)
let put f v =
  if f.kind.[0] = '(' then
    Fmt.str "{ let v: &[u8] = %s; out[..v.len()].copy_from_slice(v); 0 }" v
  else Fmt.str "{ res[0] = (%s) as i64; 0 }" v

(* The glue of case [i], over the module [m]. The operations, numbered as
   [Diff_rust] numbers them: 0 validate; 1 decode, the record encoded into
   [out]; 2 a getter; 3 [Valid::at], or [Valid::new] at offset 0, then a read;
   4 decode the canonical bytes
   in [buf], then encode them into [out] at [off]; 5 decode the canonical
   bytes, then set each field into [out]; 6 a bitfield from its word. *)
let pp_case ppf (i, fields) =
  let m = Fmt.str "c%d" i in
  let indexed = List.mapi (fun j f -> (j, f)) fields in
  Fmt.pf ppf "#[path = \"%s.rs\"]@\nmod %s;@\n@\n" m m;
  Fmt.pf ppf "mod g%d {@\n    use super::%s;@\n@\n" i m;
  Fmt.pf ppf "    fn index(name: &str) -> i64 {@\n        match name {@\n";
  List.iter
    (fun (j, f) -> Fmt.pf ppf "            %s => %d,@\n" (rust_string f.name) j)
    indexed;
  Fmt.pf ppf "            _ => -1,@\n        }@\n    }@\n@\n";
  Fmt.pf ppf "    error!(%s, index);@\n@\n" m;
  Fmt.pf ppf
    "    pub fn call(op: i32, field: i32, buf: &[u8], off: usize, out: &mut \
     [u8], res: &mut [i64]) -> i32 {@\n\
    \        match op {@\n\
    \            0 => match %s::validate(buf, off) { Ok(()) => 0, Err(e) => \
     err(e, res) },@\n\
    \            1 => match %s::decode(buf, off) {@\n\
    \                Ok(r) => match %s::encode(&r, out, 0) { Ok(()) => 0, \
     Err(e) => 100 + err(e, res) },@\n\
    \                Err(e) => err(e, res),@\n\
    \            },@\n"
    m m m;
  Fmt.pf ppf "            2 => match field {@\n";
  List.iter
    (fun (j, f) ->
      Fmt.pf ppf
        "                %d => match %s::get_%s(buf, off) { Ok(v) => %s, \
         Err(e) => err(e, res) },@\n"
        j m f.ident (put f "v"))
    indexed;
  Fmt.pf ppf "                _ => -1,@\n            },@\n";
  Fmt.pf ppf
    "            3 => match if off == 0 { %s::Valid::new(buf) } else { \
     %s::Valid::at(buf, off) } {@\n\
    \                Ok(v) => match field {@\n"
    m m;
  List.iter
    (fun (j, f) ->
      Fmt.pf ppf "                    %d => %s,@\n" j
        (put f (Fmt.str "v.%s()" f.ident)))
    indexed;
  Fmt.pf ppf
    "                    _ => -1,@\n\
    \                },@\n\
    \                Err(e) => err(e, res),@\n\
    \            },@\n";
  Fmt.pf ppf
    "            4 => match %s::decode(buf, 0) {@\n\
    \                Ok(r) => match %s::encode(&r, out, off) { Ok(()) => 0, \
     Err(e) => err(e, res) },@\n\
    \                Err(e) => 200 + err(e, res),@\n\
    \            },@\n"
    m m;
  Fmt.pf ppf
    "            5 => match %s::decode(buf, 0) {@\n\
    \                Ok(r) => {@\n"
    m;
  List.iter
    (fun f ->
      Fmt.pf ppf
        "                    if let Err(e) = %s::set_%s(out, 0, %s) { return \
         err(e, res); }@\n"
        m f.ident (arg f))
    fields;
  Fmt.pf ppf
    "                    0@\n\
    \                }@\n\
    \                Err(e) => 200 + err(e, res),@\n\
    \            },@\n";
  Fmt.pf ppf "            6 => match field {@\n";
  List.iter
    (fun (j, f) ->
      if f.kind = "Diff_rust.Bits" then
        Fmt.pf ppf
          "                %d => match %s::get_%s_word(buf, off) { Ok(w) => { \
           res[0] = %s::%s_of_word(w) as i64; 0 } Err(e) => err(e, res) },@\n"
          j m f.ident m f.ident)
    indexed;
  Fmt.pf ppf
    "                _ => -1,@\n\
    \            },@\n\
    \            _ => -1,@\n\
    \        }@\n\
    \    }@\n\
     }@\n\
     @\n"

let pp_dispatch ppf n =
  Fmt.pf ppf
    "/// Runs operation [op] of case [case] on [buf] at [off].@\n\
     ///@\n\
     /// # Safety@\n\
     ///@\n\
     /// [buf], [out] and [res] point to [len], [out_len] and 4 valid bytes, \
     [i64]s.@\n\
     #[no_mangle]@\n\
     pub unsafe extern \"C\" fn wire_rs_call(case: i32, op: i32, field: i32, \
     buf: *const u8, len: usize, off: usize, out: *mut u8, out_len: usize, \
     res: *mut i64) -> i32 {@\n\
    \    let buf = core::slice::from_raw_parts(buf, len);@\n\
    \    let out = core::slice::from_raw_parts_mut(out, out_len);@\n\
    \    let res = core::slice::from_raw_parts_mut(res, 4);@\n\
    \    match case {@\n";
  for i = 0 to n - 1 do
    Fmt.pf ppf "        %d => g%d::call(op, field, buf, off, out, res),@\n" i i
  done;
  Fmt.pf ppf "        _ => -1,@\n    }@\n}@\n"

(* The scanners of a codec, as test/diff/gen_ocaml.ml writes them for OCaml:
   every output, every other output and, for a structured case, none, which
   still makes every check. *)
let scan_variants ~validate c =
  let all = List.map fst (Wire_ocaml.scanner_fields c) in
  let selected = List.filteri (fun i _ -> i mod 2 = 0) all in
  [ ("full", None, all); ("selected", Some selected, selected) ]
  @ if validate then [ ("validate", Some [], []) ] else []

type scanner = { variant : string; outputs : string list; src : string }

let scanners ~validate ~label c =
  List.map
    (fun (variant, fields, outputs) ->
      { variant; outputs; src = Wire_rust.scanner ?fields ~codec:label c })
    (scan_variants ~validate c)

let structured =
  List.map
    (fun (Diff_codecs.Scan c) ->
      (c.label, scanners ~validate:true ~label:c.label c.codec))
    Diff_codecs.scan_cases

(* The schemas of test/ocaml whose condition, size and checks hold products
   that overflow the native int for a large 32-bit field, and the one whose
   decision tree reaches a test from two paths. *)
let schemas =
  [
    ("sized", scanners ~validate:true ~label:"sized" Schemas.sized);
    ("overflow", scanners ~validate:true ~label:"overflow" Schemas.overflow);
    ("shared", scanners ~validate:true ~label:"shared" Schemas.shared);
    ("skipped", scanners ~validate:true ~label:"skipped" Schemas.skipped);
  ]

let contains s sub =
  let n = String.length sub in
  let rec go i =
    i + n <= String.length s
    && (String.equal (String.sub s i n) sub || go (i + 1))
  in
  go 0

(* Each sampled shape the OCaml scanner accepts. The Rust one refuses only
   the outputs that Rust alone spells alike, once its keywords are escaped. *)
let sampled =
  List.filter_map
    (fun (label, Fuzz_gen.Pack g) ->
      let c = Fuzz_gen.codec g in
      match Wire_ocaml.scanner_fields c with
      | exception Invalid_argument _ -> None
      | _ -> (
          match scanners ~validate:false ~label c with
          | l -> Some (label, l)
          | exception Invalid_argument msg
            when contains msg "both define the Rust field" ->
              None
          | exception Invalid_argument msg ->
              Fmt.failwith
                "gen_rust: the Rust scanner refuses %s, which the OCaml one \
                 accepts: %s"
                label msg))
    Diff_ocaml.scan_codecs

(* The glue of scanner [i]: its outputs, in order, as [i64]s in [res]. *)
let pp_scan ppf (i, outputs) =
  Fmt.pf ppf "#[path = \"scan%d.rs\"]@\nmod scan%d;@\n@\n" i i;
  Fmt.pf ppf
    "fn scan_%d(buf: &[u8], off: usize, len: usize, res: &mut [i64]) -> i32 {@\n\
    \    match scan%d::decode(buf, off, len) {@\n\
    \        Some(f) => {@\n"
    i i;
  List.iteri
    (fun j o ->
      Fmt.pf ppf "            res[%d] = f.%s as i64;@\n" j (Wire_rust.ident o))
    outputs;
  Fmt.pf ppf "            1@\n        }@\n        None => 0,@\n    }@\n}@\n@\n"

let pp_scan_dispatch ppf n =
  Fmt.pf ppf
    "/// Runs scanner [case] on the [flen] bytes at [off] in [buf], its outputs@\n\
     /// in [res]: 1 when it accepts them, 0 when it does not.@\n\
     ///@\n\
     /// # Safety@\n\
     ///@\n\
     /// [buf] and [res] point to [len] valid bytes and [nres] valid [i64]s.@\n\
     #[no_mangle]@\n\
     pub unsafe extern \"C\" fn wire_rs_scan(case: i32, buf: *const u8, len: \
     usize, off: i64, flen: i64, res: *mut i64, nres: usize) -> i32 {@\n\
    \    let buf = core::slice::from_raw_parts(buf, len);@\n\
    \    let res = core::slice::from_raw_parts_mut(res, nres);@\n\
    \    if off < 0 || flen < 0 {@\n\
    \        return 0;@\n\
    \    }@\n\
    \    let (off, flen) = (off as usize, flen as usize);@\n\
    \    match case {@\n";
  for i = 0 to n - 1 do
    Fmt.pf ppf "        %d => scan_%d(buf, off, flen, res),@\n" i i
  done;
  Fmt.pf ppf "        _ => -1,@\n    }@\n}@\n"

(* Each group's scanners, numbered from [first]. *)
let pp_scan_index ppf ~name ~first groups =
  Fmt.pf ppf "let %s : (string * Diff_rust.scan list) list =@\n  [@\n" name;
  let next =
    List.fold_left
      (fun i (label, l) ->
        Fmt.pf ppf "    (%S, [@\n" label;
        let i =
          List.fold_left
            (fun i s ->
              Fmt.pf ppf
                "      { Diff_rust.scan_id = %d; variant = %S; outputs = [ %a \
                 ] };@\n"
                i s.variant
                Fmt.(list ~sep:(any "; ") (fun ppf -> pf ppf "%S"))
                s.outputs;
              i + 1)
            i l
        in
        Fmt.pf ppf "    ]);@\n";
        i)
      first groups
  in
  Fmt.pf ppf "  ]@\n@\n";
  next

let () =
  let dir = Sys.argv.(1) in
  if not (Sys.file_exists dir) then Sys.mkdir dir 0o755;
  let accepted, refused =
    List.partition_map
      (fun (label, Fuzz_gen.Pack g) ->
        let c = Fuzz_gen.codec g in
        match Wire_rust.rs ~codec:label c with
        | src -> Left (label, fields c, Wire.Codec.wire_size c, src)
        | exception Invalid_argument msg -> Right (label, msg))
      Diff_ocaml.codecs
  in
  List.iteri
    (fun i (_, _, _, src) ->
      write (Filename.concat dir (Fmt.str "c%d.rs" i)) src)
    accepted;
  let lib = Buffer.create 65536 in
  let ppf = Format.formatter_of_buffer lib in
  Fmt.pf ppf "%s@\n" prelude;
  List.iteri (fun i (_, fields, _, _) -> pp_case ppf (i, fields)) accepted;
  pp_dispatch ppf (List.length accepted);
  let all = List.concat_map snd (structured @ schemas @ sampled) in
  List.iteri
    (fun i s ->
      write (Filename.concat dir (Fmt.str "scan%d.rs" i)) s.src;
      pp_scan ppf (i, s.outputs))
    all;
  pp_scan_dispatch ppf (List.length all);
  Fmt.flush ppf ();
  write (Filename.concat dir "lib.rs") (Buffer.contents lib);
  let idx = Buffer.create 65536 in
  let ppf = Format.formatter_of_buffer idx in
  Fmt.pf ppf
    "(* Generated by test/diff/gen_rust.exe from the codecs of \
     Diff_ocaml.codecs. *)@\n\
     @\n\
     let name = \"rust\"@\n\
     @\n\
     let covered : (string * Diff_rust.case) list =@\n\
    \  [@\n";
  List.iteri
    (fun i (label, fields, size, _) ->
      Fmt.pf ppf
        "    (%S, { Diff_rust.id = %d; size = %d; fields = [| %a |] });@\n"
        label i size
        Fmt.(
          list ~sep:(any "; ") (fun ppf f ->
              pf ppf "{ Diff_rust.name = %S; kind = %s }" f.name f.kind))
        fields)
    accepted;
  Fmt.pf ppf "  ]@\n@\nlet refused : (string * string) list =@\n  [@\n";
  List.iter
    (fun (label, msg) -> Fmt.pf ppf "    (%S, %S);@\n" label msg)
    refused;
  Fmt.pf ppf "  ]@\n@\n";
  let first = pp_scan_index ppf ~name:"scanners" ~first:0 structured in
  let first = pp_scan_index ppf ~name:"schema_scanners" ~first schemas in
  ignore (pp_scan_index ppf ~name:"sampled_scanners" ~first sampled);
  Fmt.flush ppf ();
  write "rust_index.ml" (Buffer.contents idx)
