(* tables.exe prints WireGen.Tables.fst: the rules of WireGen.OCaml
   instantiated at the literal operands the emitter prints, so Z3 matches
   them on the code as written. *)

(* [pow2 k] in decimal: 2^63 and 2^64 do not fit an OCaml [int]. *)
let pow2 k =
  let digits = Bytes.make 21 '0' in
  Bytes.set digits 20 '1';
  for _ = 1 to k do
    let carry = ref 0 in
    for i = 20 downto 0 do
      let d = ((Char.code (Bytes.get digits i) - 48) * 2) + !carry in
      Bytes.set digits i (Char.chr (48 + (d mod 10)));
      carry := d / 10
    done
  done;
  let s = Bytes.to_string digits in
  let rec first i = if i < 20 && s.[i] = '0' then first (i + 1) else i in
  let i = first 0 in
  String.sub s i (21 - i)

let conj = " /\\\n    "
let seq = ";\n    "

let pw =
  String.concat conj
    (List.init 65 (fun k -> Fmt.str "pow2 %d == %s" k (pow2 k)))

(* The masks [2^k - 1], with [k]. *)
let masks = List.init 62 (fun i -> (i + 1, (1 lsl (i + 1)) - 1))

(* The words of [m] bytes at byte [k] of an 8-byte load. *)
let words =
  List.concat_map
    (fun m -> List.init (9 - m) (fun k -> (k, m)))
    [ 1; 2; 3; 4; 5; 6; 7 ]

let land_fact (k, m) =
  Fmt.str
    "(forall (a:P.int). {:pattern (P.land a %d)} a >= 0 ==> P.land a %d == a \
     %% %s) /\\ (forall (w:P.int64). {:pattern (P.land (P.to_int w) %d)} \
     P.land (P.to_int w) %d == w %% %s)"
    m m (pow2 k) m m (pow2 k)

(* A word that ends the load is read with no shift. *)
let word_fact (k, m) =
  let sh = 8 * (8 - k - m) in
  let t =
    if sh = 0 then "P.i64be b o"
    else Fmt.str "P.shift_right_logical (P.i64be b o) %d" sh
  in
  let top = if k = 0 then Fmt.str " /\\ %s == be b o %d" t m else "" in
  Fmt.str
    "(forall (b:P.buf) (o:P.int). {:pattern (%s)} (0 <= o /\\ o + 8 <= \
     P.length b) ==> (%s %% %s == be b (o + %d) %d%s))"
    t t
    (pow2 (8 * m))
    k m top

let lands = String.concat conj (List.map land_fact masks)
let word_facts = String.concat conj (List.map word_fact words)

let land_lits =
  String.concat seq
    (List.map (fun (k, m) -> Fmt.str "P.land_lit %d %d" k m) masks)

let word_lits =
  String.concat seq
    (List.map
       (fun (k, m) ->
         let sh = 8 * (8 - k - m) in
         if sh = 0 then Fmt.str "P.word_end %d %d %s" k m (pow2 (8 * m))
         else Fmt.str "P.word_lit %d %d %d %s" k m sh (pow2 (8 * m)))
       words)

let () =
  print_string
    (String.concat ""
       [
         "module WireGen.Tables\n\n";
         "(* Generated by scripts/fstar-gen/tables.exe. The rules of \
          WireGen.OCaml\n";
         "   at the literal operands the emitter prints (a shift by 56, a mask\n";
         "   0xff), so Z3 matches them on the code as written. A proof poses\n";
         "   [tables ()]. *)\n\n";
         "open WireGen.Lib\nmodule P = WireGen.OCaml\n\n";
         "let pow2_table () : Lemma (\n    ";
         pw;
         ")\n  = assert_norm (\n    ";
         pw;
         ")\n\nlet land_table () : Lemma (\n    ";
         lands;
         ")\n  = pow2_table ();\n    ";
         land_lits;
         "\n\nlet word_table () : Lemma (\n    ";
         word_facts;
         ")\n  = pow2_table ();\n    ";
         word_lits;
         "\n\nlet tables () : Lemma (\n    (";
         pw;
         ") /\\\n    (";
         lands;
         ") /\\\n    (";
         word_facts;
         "))\n  = pow2_table (); land_table (); word_table ()\n";
       ])
