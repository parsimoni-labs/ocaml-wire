#!/usr/bin/env python3
# Writes WireGen.Tables.fst: the rules of WireGen.OCaml instantiated at the
# literal operands the emitter prints, so Z3 matches them on the code as
# written. Run once; the output is committed.
AND = " /\\\n    "
pw = AND.join(f"pow2 {k} == {2**k}" for k in range(65))
masks = [(k, 2**k - 1) for k in range(1, 63)]
words = [(k, m) for m in range(1, 8) for k in range(0, 9 - m)]

def land_fact(m):
    return (f"(forall (a:P.int). {{:pattern (P.land a {m})}} a >= 0 ==> P.land a {m} == a % {m+1}) /\\ "
            f"(forall (w:P.int64). {{:pattern (P.land (P.to_int w) {m})}} P.land (P.to_int w) {m} == w % {m+1})")

def word_fact(k, m):
    sh = 8 * (8 - k - m)
    t = f"P.shift_right_logical (P.i64be b o) {sh}"
    top = f" /\\ {t} == be b o {m}" if k == 0 else ""
    return (f"(forall (b:P.buf) (o:P.int). {{:pattern ({t})}} (0 <= o /\\ o + 8 <= P.length b) ==> "
            f"({t} % {2**(8*m)} == be b (o + {k}) {m}{top}))")

out = f"""module WireGen.Tables

(* Generated by tables.py. The rules of WireGen.OCaml at the literal
   operands the emitter prints (a shift by 56, a mask 0xff), so Z3 matches
   them on the code as written. A proof poses [tables ()]. *)

open WireGen.Lib
module P = WireGen.OCaml

let pow2_table () : Lemma (
    {pw})
  = assert_norm (
    {pw})

let land_table () : Lemma (
    {AND.join(land_fact(m) for k, m in masks)})
  = pow2_table ();
    {(";" + chr(10) + "    ").join(f"P.land_lit {k} {m}" for k, m in masks)}

let word_table () : Lemma (
    {AND.join(word_fact(k, m) for k, m in words)})
  = pow2_table ();
    {(";" + chr(10) + "    ").join(f"P.word_lit {k} {m} {8*(8-k-m)} {2**(8*m)}" for k, m in words)}

let tables () : Lemma (
    ({pw}) /\\
    ({AND.join(land_fact(m) for k, m in masks)}) /\\
    ({AND.join(word_fact(k, m) for k, m in words)}))
  = pow2_table (); land_table (); word_table ()
"""
open("WireGen.Tables.fst", "w").write(out)
